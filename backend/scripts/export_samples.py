"""Write docs/sample_results.md from real pipeline runs (nothing is edited by hand).

    python scripts/export_samples.py            # the default sample questions
    python scripts/export_samples.py "question 1" "question 2" ...

Answers already asked (e.g. by evaluate.py or the UI) come from the response
cache, so regenerating this file costs no LLM calls.
"""

from __future__ import annotations

import json
import sys
import time

from taxqa.answering.schemas import Answer
from taxqa.core.config import ROOT, settings
from taxqa.services.qa_pipeline import QAPipeline

DEFAULT = [
    ("House property (the example from the brief)",
     "I own a residential property that I have rented out. Can I claim a 30% deduction on the annual value of the property? "
     "I also have a housing loan on this property. Can I claim a deduction for the interest paid on the loan? "
     "Which sections of the Income-tax Act apply?", "result-1.png"),
    ("Chapter VI-A deduction",
     "What deductions are available for life insurance premium and provident fund contributions?", "result-2.png"),
    ("Exemption and definition", "Is agricultural income taxable?", "result-3.png"),
    ("Question outside the Act (abstention)", "What is the GST rate on restaurant services?", "result-4.png"),
]
STATUS = {"answered": "Answered", "partial": "Partially answered", "insufficient": "Insufficient support",
          "out_of_scope": "Out of scope", "error": "Error"}


def cell(s) -> str:
    return " ".join(str(s or "").replace("|", "\\|").split())


def pages(c) -> str:
    if not c.page_start:
        return "n/a"
    return f"p. {c.page_start}" if c.page_start == c.page_end else f"pp. {c.page_start}-{c.page_end}"


def render(title: str, a: Answer, shot: str) -> list[str]:
    kept = [p for p in a.points if not p.removed]
    conf = f"{a.confidence.score}% ({a.confidence.band})" if a.confidence.score is not None else "n/a"
    out = [f"## {title}", "", f"**Question:** {a.question}", "",
           f"**Status:** {STATUS.get(a.status, a.status)} · **Confidence:** {conf}", "",
           f"**Answer:** {a.summary or '(no answer)'}", ""]
    for p in kept:
        out.append(f"- **{cell(p.heading)}**: {cell(p.statement)}")
    if kept:
        out += ["", "| Answer statement | Statutory reference | Quote (verbatim from the Act) | Source document | PDF page | Verified |",
                "|---|---|---|---|---|---|"]
        for p in kept:
            for c in p.citations:
                checks = "Yes" if c.valid else ("Partly" if c.found_in_sources else "No")
                out.append(f"| {cell(p.heading)} | {cell(c.provision)} | \"{cell(c.quote)}\" | "
                           f"{cell(c.source_document or a.source_document)} | {pages(c)} | {checks} |")
    if a.not_covered:
        out += ["", "**Not covered by the retrieved provisions:** " + "; ".join(a.not_covered)]
    if a.caveats:
        out += ["", "**Caveats:** " + "; ".join(a.caveats)]
    if a.warnings:
        out += ["", "**Warnings shown to the user:**"] + [f"- {w}" for w in a.warnings]
    removed = [p for p in a.points if p.removed]
    if removed or a.summary_removed:
        out += ["", f"**Removed by the verifier:** {len(removed)} statement(s), {len(a.summary_removed)} summary sentence(s)."]
    if not kept and a.sources:
        out += ["", "Closest provisions shown for reference only: " + ", ".join(s.label for s in a.sources[:5])]
    if (ROOT.parent / "docs" / "screenshots" / shot).exists():
        out += ["", f"![{title}](screenshots/{shot})"]
    return out + ["", "---", ""]


def main() -> int:
    items = [(f"Question {i}", q, f"custom-{i}.png") for i, q in enumerate(sys.argv[1:], 1)] or DEFAULT
    p = QAPipeline(settings)
    report = json.loads(settings.processed_dir.joinpath("ingest_report.json").read_text(encoding="utf-8"))
    answers = [(t, p.ask(q), shot) for t, q, shot in items]
    models = next((a.models for _, a, _ in answers if "generator" in a.models), answers[0][1].models)
    lines = [
        "# Sample results", "",
        "Every result below is generated by `backend/scripts/export_samples.py` from real runs of the pipeline; "
        "nothing is edited by hand. Re-run the script to reproduce it (cached answers cost no LLM calls).", "",
        f"- **Generated:** {time.strftime('%Y-%m-%d')}",
        f"- **Source document:** {settings.source_name} ({settings.source_edition})",
        f"- **PDF:** {report.get('source_pdf')} · {report.get('pages')} pages · SHA-256 `{report.get('source_sha256')}`",
        "- **Models:** " + ", ".join(f"{k} = {v.replace(' (cached)', '')}" for k, v in models.items()),
        "- **Verified** means the cited section was retrieved, the sub-division / proviso / Explanation marker "
        "is present in its text, and the quote matches the statute.", "", "---", "",
    ]
    for t, a, shot in answers:
        lines += render(t, a, shot)
    out = ROOT.parent / "docs" / "sample_results.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out} ({len(answers)} results)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
